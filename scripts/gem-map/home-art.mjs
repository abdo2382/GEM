// Draws the museum map's picture for the homepage: the real outlines and one real walk, as a few
// SVG paths in src/site/homeMap.ts, so the homepage does not need the whole map file.
//   node scripts/gem-map/home-art.mjs      (run after build.mjs)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildGraph, findRoute } from '../../src/museum-map/astar.ts'
import { boundsOf } from '../../src/museum-map/camera.ts'
import { polygonArea, simplify } from '../../src/museum-map/geo.ts'

const here = dirname(fileURLToPath(import.meta.url))
const map = JSON.parse(readFileSync(join(here, '..', '..', 'src', 'museum-map', 'data', 'gem-complex.json'), 'utf8'))
const place = (id) => map.places.find((p) => p.id === id)
const g = buildGraph(map)

const d = (points, close = false) => 'M' + points.map((p) => `${Math.round(p[0])} ${Math.round(p[1])}`).join('L') + (close ? 'Z' : '')

// The walk the picture shows: from the visitor entrance to the Conservation Centre.
const route = findRoute(g, place('ticketing-entrance').node, place('conservation-centre').node)
const routePoints = simplify(route.nodes.map((n) => g.pos[n]), 2.5)

const placeBuildings = new Set(map.places.flatMap((p) => (p.building === undefined ? [] : [p.building])))
const mainBuilding = place('main-building').building
const b = map.scenery.buildings
const own = [...placeBuildings].filter((i) => i !== mainBuilding)
const rest = b.map((x, i) => [x, i]).filter(([x, i]) => !placeBuildings.has(i) && polygonArea(x.o) > 350)

const frame = boundsOf([...map.places.map((p) => p.at), ...[...placeBuildings].flatMap((i) => b[i].o)])
const art = {
  walls: map.scenery.walls.map((w) => d(simplify(w.p, 3))).join(''),
  greens: map.scenery.greens.filter((x) => polygonArea(x.o) > 700).map((x) => d(simplify(x.o, 3), true)).join(''),
  buildings: rest.map(([x]) => d(simplify(x.o, 2.5), true)).join(''),
  places: own.map((i) => d(simplify(b[i].o, 1.5), true)).join(''),
  main: d(simplify(b[mainBuilding].o, 1.5), true),
  route: d(routePoints),
  dots: map.places.filter((p) => p.kind !== 'service').map((p) => [Math.round(p.at[0]), Math.round(p.at[1])]),
}

// A square frame around the places, cropped to fit by the door that shows it.
const pad = 70
let [w, h] = [frame.maxX - frame.minX + 2 * pad, frame.maxY - frame.minY + 2 * pad]
const cx = (frame.minX + frame.maxX) / 2
const cy = (frame.minY + frame.maxY) / 2
if (w > h) h = w
else w = h
art.viewBox = `${Math.round(cx - w / 2)} ${Math.round(cy - h / 2)} ${Math.round(w)} ${Math.round(h)}`

const out = `// Generated by scripts/gem-map/home-art.mjs from the museum map data. Do not edit by hand.
// Map data © OpenStreetMap contributors (ODbL). The route is a real A* walk on that data.
export const HOME_MAP = ${JSON.stringify(art, null, 2)} as const
`
writeFileSync(join(here, '..', '..', 'src', 'site', 'homeMap.ts'), out)
console.log(`wrote src/site/homeMap.ts (${(Buffer.byteLength(out) / 1024).toFixed(1)} KB); walk ${route.length.toFixed(0)} m`)
